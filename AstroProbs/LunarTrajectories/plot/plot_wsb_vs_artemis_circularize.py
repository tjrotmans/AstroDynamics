    z_lim = max(float(np.max(np.abs(cap_z))), float(np.max(np.abs(art_z)))) + 50_000
    z_lim = max(z_lim, r_lim * 0.20)
    ax3.set_xlim(-r_lim, r_lim); ax3.set_ylim(-r_lim, r_lim); ax3.set_zlim(-z_lim, z_lim)
    ax3.set_xlabel("X [km]", labelpad=1, fontsize=11)
    ax3.set_ylabel("Y [km]", labelpad=1, fontsize=11)
    ax3.set_zlabel("Z [km]", labelpad=1, fontsize=11)
    ax3.set_box_aspect([1.8, 1.8, max(0.35, z_lim / r_lim * 1.8)])
    ax3.view_init(elev=22, azim=-50)

    # ── Static 3D objects ─────────────────────────────────────────────────────
    sx, sy, sz = sphere_surface(R_EARTH, nu=48, nv=24)
