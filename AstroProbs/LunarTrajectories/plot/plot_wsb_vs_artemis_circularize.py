def main() -> None:
    print("Loading Artemis II trajectory ...")
    (R0, u_sun_eci,
     art_t, art_x, art_y, art_z,
     art_mx, art_my, art_mz) = load_artemis()
    print(f"  Artemis: {len(art_t)} points, T+{art_t[-1]:.1f} d")

    # Artemis departure time (absolute seconds) for LOI time conversion
    art_df   = pd.read_csv(ART_CSV)
    art_t_s0 = float(art_df["time_s"].iloc[0])

    print("Loading DE440S Moon ephemeris ...")
    (ephem_t, ephem_mx, ephem_my, ephem_mz, _, _, _) = load_moon_ephem(art_t_s0)
    print(f"  Ephemeris: {len(ephem_t)} pts, t=[{ephem_t[0]:.1f}, {ephem_t[-1]:.1f}] d")

    # Artemis LOI time
    _art_loi_t0_s = float(pd.read_csv(ART_LOI_CSV, nrows=1)["time_s"].iloc[0])
    _art_loi_days = (_art_loi_t0_s - art_t_s0) / 86_400.0
    print(f"  Artemis LOI @ {_art_loi_days:.2f} d from CSV start")

    # WSB burn time from circularize_info (needed for synodic N selection)
    _wsb_circ_info_pre = load_circ_info(CIRC_INFO)
    _wsb_burn_time_days = float(_wsb_circ_info_pre.get("Burn time (days)", 0) or 0)

    print("Computing WSB departure epoch (circular-Moon, same as wsb_vs_artemis.py) ...")
    meta = pd.read_csv(WSB_HIF_CSV, nrows=1).iloc[0]
    _theta_sun_deg = float(meta["theta_sun_deg"])
    departure_offset_days, R0_wsb = compute_wsb_epoch_simple(
        _theta_sun_deg, R0, u_sun_eci,
        burn_time_days=_wsb_burn_time_days,
        target_loi_days=_art_loi_days + 15.0,
    )
    art_csv_start_utc = TLI_UTC + datetime.timedelta(seconds=art_t_s0)
    wsb_dep_utc       = art_csv_start_utc + datetime.timedelta(days=departure_offset_days)
    print(f"  WSB departure : {wsb_dep_utc.strftime('%Y-%m-%d %H:%M UTC')}")
    print(f"  Offset        : {departure_offset_days:+.2f} d from Artemis CSV start")

    print(f"Loading WSB capture trajectory ({CAPTURE_CSV.name}) ...")
    cap_t, cap_x, cap_y, cap_z, cap_mx, cap_my, cap_mz = \
        _load_wsb_nd_csv(CAPTURE_CSV, R0_wsb, departure_offset_days)
    print(f"  {len(cap_t)} points, T+{cap_t[-1] - departure_offset_days:.1f} d flight")

    burn_t = float(cap_t[-1])
    print(f"  WSB LOI burn time: {burn_t:.2f} days")

    print(f"Loading WSB ECI LOI orbit ({LOI_CSV.name}) ...")
    loi_t, loi_x, loi_y, loi_z, loi_mx, loi_my, loi_mz = load_wsb_loi_eci(art_t_s0)
    print(f"  {len(loi_t)} points, {loi_t[-1] - loi_t[0]:.1f} d of lunar orbit")

    wsb_circ_info = _wsb_circ_info_pre
    if wsb_circ_info:
        print(f"  WSB LOI dV = {wsb_circ_info.get('LOI DeltaV km/s','?')} km/s  "
              f"alt = {wsb_circ_info.get('Burn altitude km','?')} km")

    print(f"Loading Artemis LOI orbit ({ART_LOI_CSV.name}) ...")
    art_loi_t, art_loi_x, art_loi_y, art_loi_z, \
    art_loi_mx, art_loi_my, art_loi_mz = load_artemis_loi(art_t_s0)
    burn_t_art = float(art_loi_t[0])
    print(f"  {len(art_loi_t)} points, burn at T+{burn_t_art:.2f} d, "
          f"{art_loi_t[-1] - art_loi_t[0]:.1f} d of lunar orbit")

    art_circ_info = load_circ_info(ART_CIRC_INFO)
    if art_circ_info:
        print(f"  Artemis LOI dV = {art_circ_info.get('LOI DeltaV km/s','?')} km/s  "
              f"alt = {art_circ_info.get('Burn altitude km','?')} km")

    # ── Hohmann TLI ΔV comparison ─────────────────────────────────────────────
    # WSB: single Hohmann from circular 378 km to WSB apogee.
    wsb_apo_km = float(np.max(np.sqrt(cap_x**2 + cap_y**2 + cap_z**2)))
    wsb_tli_dv = hohmann_tli_dv(R_PARK_KM, wsb_apo_km)
    # Artemis: (1) Hohmann from circular 378 km → parking orbit apogee 109 400 km,
    #          (2) TLI burn from parking orbit (from config: 422.4 m/s).
    art_parking_dv = hohmann_tli_dv(R_PARK_KM, ART_PARKING_APO_KM)
    art_tli_dv     = ART_TLI_KMS
    print(f"  WSB apogee: {wsb_apo_km/1e3:.1f}e3 km  ->  TLI dV = {wsb_tli_dv:.4f} km/s")
    print(f"  Artemis: Prk dV = {art_parking_dv:.4f} km/s  +  TLI = {art_tli_dv:.4f} km/s")

    CIRC_DIR.mkdir(parents=True, exist_ok=True)

    de440s_moon_t = ephem_t
    de440s_moon_x = ephem_mx
    de440s_moon_y = ephem_my
    de440s_moon_z = ephem_mz
    print(f"  Moon track: {len(de440s_moon_t)} pts, "
          f"t=[{de440s_moon_t[0]:.2f}, {de440s_moon_t[-1]:.1f}] days")

    print("Building interactive Plotly HTML ...")
    fig = build_plotly(
        cap_t, cap_x, cap_y, cap_z, cap_mx, cap_my, cap_mz,
        loi_t, loi_x, loi_y, loi_z, loi_mx, loi_my, loi_mz,
        art_t, art_x, art_y, art_z, art_mx, art_my, art_mz,
        art_loi_t, art_loi_x, art_loi_y, art_loi_z,
        art_loi_mx, art_loi_my, art_loi_mz,
        burn_t, burn_t_art,
        wsb_circ_info, art_circ_info, R0,
        wsb_tli_dv=wsb_tli_dv, art_tli_dv=art_tli_dv,
        art_parking_dv=art_parking_dv, art_t_s0=art_t_s0,
        de440s_moon_t=de440s_moon_t, de440s_moon_x=de440s_moon_x,
        de440s_moon_y=de440s_moon_y, de440s_moon_z=de440s_moon_z,
    )
    fig.write_html(str(OUT_HTML), auto_play=False)
    print(f"Saved -> {OUT_HTML}")

    print("Building MP4 video ...")
    build_video(
        cap_t, cap_x, cap_y, cap_z, cap_mx, cap_my, cap_mz,
        loi_t, loi_x, loi_y, loi_z, loi_mx, loi_my, loi_mz,
        art_t, art_x, art_y, art_z, art_mx, art_my, art_mz,
        art_loi_t, art_loi_x, art_loi_y, art_loi_z,
        art_loi_mx, art_loi_my, art_loi_mz,
        burn_t, burn_t_art,
        wsb_circ_info, art_circ_info, R0,
        wsb_tli_dv=wsb_tli_dv, art_tli_dv=art_tli_dv,
        art_parking_dv=art_parking_dv, art_t_s0=art_t_s0,
        de440s_moon_t=de440s_moon_t, de440s_moon_x=de440s_moon_x,
        de440s_moon_y=de440s_moon_y, de440s_moon_z=de440s_moon_z,
    )


if __name__ == "__main__":
    main()
