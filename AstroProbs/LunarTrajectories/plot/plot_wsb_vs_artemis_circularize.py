                go.Scatter(x=ltx2,  y=lty2),
                go.Scatter(x=atx2,  y=aty2),
                go.Scatter(x=altx2, y=alty2),
                # 2D dots: cap, loi, art, art_loi
                go.Scatter(x=[float(cx - _cx_mc)],  y=[float(cy - _cy_mc)]),
                go.Scatter(x=loi_2d[0],           y=loi_2d[1]),
                go.Scatter(x=[float(ax - al_mx)], y=[float(ay - al_my)]),
                go.Scatter(x=al_2d[0],            y=al_2d[1]),
