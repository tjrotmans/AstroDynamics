def load_circ_info(path: pathlib.Path) -> dict:
    info = {}
    if not path.exists():
        return info
    for line in path.read_text().splitlines():
        if ":" in line:
            k, _, v = line.partition(":")
            info[k.strip()] = v.strip()
    return info


def load_epoch_info() -> tuple:
    """Read dep_offset_days and R0_wsb from Rust-generated epoch_info.txt."""
    info = {}
    for line in EPOCH_INFO.read_text().splitlines():
        if ":" in line:
            k, _, v = line.partition(":")
            info[k.strip()] = v.strip()
    dep_offset_days = float(info["dep_offset_days"])
    R0_wsb = np.array([
        [float(x) for x in info["R0_wsb_col0"].split()],
        [float(x) for x in info["R0_wsb_col1"].split()],
        [float(x) for x in info["R0_wsb_col2"].split()],
    ]).T   # columns → matrix
    return dep_offset_days, R0_wsb


