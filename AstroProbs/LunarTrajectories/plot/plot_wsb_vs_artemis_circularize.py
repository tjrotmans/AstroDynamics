def sphere_surface(r, nu=40, nv=20):
    u = np.linspace(0, 2 * np.pi, nu)
    v = np.linspace(0, np.pi, nv)
    return (r * np.outer(np.cos(u), np.sin(v)),
            r * np.outer(np.sin(u), np.sin(v)),
            r * np.outer(np.ones(nu), np.cos(v)))


def downsample(arr, n):
    idx = np.unique(np.round(np.linspace(0, len(arr) - 1, n)).astype(int))
    return arr[idx]


def interp_pos(t_arr, x, y, z, t_query):
    tq = np.clip(t_query, t_arr[0], t_arr[-1])
    return np.interp(tq, t_arr, x), np.interp(tq, t_arr, y), np.interp(tq, t_arr, z)


def hohmann_tli_dv(r_park_km: float, r_apo_km: float,
                   gm_earth: float = 398_600.4418) -> float:
    """ΔV to raise apogee from circular parking orbit to r_apo via Hohmann."""
    a_t    = (r_park_km + r_apo_km) / 2.0
    v_circ = np.sqrt(gm_earth / r_park_km)
    v_tli  = np.sqrt(gm_earth * (2.0 / r_park_km - 1.0 / a_t))
    return v_tli - v_circ


