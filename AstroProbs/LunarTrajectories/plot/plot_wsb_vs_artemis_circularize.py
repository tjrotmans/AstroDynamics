def _interp_ephem(t_days: float, ephem_t, ex, ey, ez) -> np.ndarray:
    """Interpolate ephemeris position (km) at t_days from Artemis CSV start."""
    return np.array([np.interp(t_days, ephem_t, ex),
                     np.interp(t_days, ephem_t, ey),
                     np.interp(t_days, ephem_t, ez)])


def compute_wsb_epoch_simple(
    theta_sun_deg: float,
    R0: np.ndarray,
    u_sun_eci: np.ndarray,
    burn_time_days: float = 0.0,
    target_loi_days: float = 5.0,
) -> tuple:
    """Circular-Moon WSB epoch — mirrors plot_wsb_vs_artemis.py's compute_wsb_epoch,
    extended with synodic N selection to place the LOI near target_loi_days."""
    if np.isnan(theta_sun_deg):
        return 0.0, R0.copy()
    sun_in_em         = R0.T @ u_sun_eci
    theta_sun_artemis = np.degrees(np.arctan2(sun_in_em[1], sun_in_em[0]))
    delta_theta       = ((theta_sun_deg - theta_sun_artemis) + 180.0) % 360.0 - 180.0
    offset_days_base  = delta_theta / (-360.0 / SYNODIC_DAYS)
    target_dep        = target_loi_days - burn_time_days
    best_N            = round((target_dep - offset_days_base) / SYNODIC_DAYS)
    offset_days       = offset_days_base + best_N * SYNODIC_DAYS
    print(f"  Synodic N={best_N:+d}: departure={offset_days:.2f} d, LOI @ {offset_days + burn_time_days:.2f} d")
    moon_angle_rad = 2.0 * np.pi * offset_days / MOON_SIDEREAL_DAYS
    ca, sa = np.cos(moon_angle_rad), np.sin(moon_angle_rad)
    new_x  = R0 @ np.array([ca, sa, 0.0])
    new_z  = R0[:, 2]
    new_y  = np.cross(new_z, new_x); new_y /= np.linalg.norm(new_y)
    R0_wsb = np.column_stack([new_x, new_y, new_z])
    return offset_days, R0_wsb


def compute_wsb_epoch(theta_sun_deg, R0, u_sun_eci,
                      ephem_t, ephem_mx, ephem_my, ephem_mz,
                      ephem_sx, ephem_sy, ephem_sz,
                      burn_time_days: float = 0.0,
                      target_loi_days: float = 5.0):
    """Find WSB departure epoch from BCR4BP Sun angle using DE440S ephemeris.

    Uses real Moon+Sun positions (interpolated from DE440S) instead of 2-body
    propagation, eliminating solar-perturbation error.

    Step 1 — mean-synodic initial guess (±14.8 d, one synodic root).
    Step 2 — pick synodic N to place WSB LOI near target_loi_days.
    Step 3 — Newton refinement: match real Sun angle to theta_sun_deg.
    Step 4 — build R0_wsb from real Moon direction at the converged epoch.
    """
    if np.isnan(theta_sun_deg):
        return 0.0, R0.copy()

    # ── Step 1: mean-synodic initial guess ──────────────────────────────────────
    sun_in_em         = R0.T @ u_sun_eci
    theta_sun_artemis = np.degrees(np.arctan2(sun_in_em[1], sun_in_em[0]))
    delta_theta       = ((theta_sun_deg - theta_sun_artemis) + 180.0) % 360.0 - 180.0
    offset_days_base  = delta_theta / (-360.0 / SYNODIC_DAYS)

    # ── Step 2: synodic N that puts WSB LOI nearest to Artemis LOI ──────────────
    target_dep  = target_loi_days - burn_time_days
    best_N      = round((target_dep - offset_days_base) / SYNODIC_DAYS)
    offset_days = offset_days_base + best_N * SYNODIC_DAYS
    print(f"  Synodic N={best_N:+d}: departure={offset_days:.2f} d, "
          f"WSB LOI @ {offset_days + burn_time_days:.2f} d  "
          f"(Artemis LOI ~ {target_loi_days:.1f} d)")
    offset_days_mean = float(offset_days)

    # ── Step 3: Newton refinement using DE440S ───────────────────────────────────
    z_em = R0[:, 2]
    for _ in range(8):
        m_wsb      = _interp_ephem(offset_days, ephem_t, ephem_mx, ephem_my, ephem_mz)
        s_wsb      = _interp_ephem(offset_days, ephem_t, ephem_sx, ephem_sy, ephem_sz)
        em_x       = m_wsb / np.linalg.norm(m_wsb)
        em_y_n     = np.cross(z_em, em_x); em_y_n /= np.linalg.norm(em_y_n)
        theta_real = np.degrees(np.arctan2(s_wsb @ em_y_n, s_wsb @ em_x))
        residual   = ((theta_sun_deg - theta_real) + 180.0) % 360.0 - 180.0
        offset_days += residual / (-360.0 / SYNODIC_DAYS)
        if abs(residual) < 1e-6:
            break
    print(f"  Newton refinement: {offset_days_mean:.4f} d -> {offset_days:.4f} d  "
          f"(delta = {(offset_days - offset_days_mean)*24:.2f} h)")

    # ── Step 4: R0_wsb from real Moon direction at departure ─────────────────────
    moon_at_wsb = _interp_ephem(offset_days, ephem_t, ephem_mx, ephem_my, ephem_mz)
    new_x  = moon_at_wsb / np.linalg.norm(moon_at_wsb)
    new_z  = R0[:, 2]
    new_y  = np.cross(new_z, new_x); new_y /= np.linalg.norm(new_y)
    R0_wsb = np.column_stack([new_x, new_y, new_z])
    return offset_days, R0_wsb


