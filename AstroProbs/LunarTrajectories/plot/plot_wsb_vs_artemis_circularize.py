    t_min    = cap_t[0]
    t_max    = min(t_min + 120.0, max(loi_t[-1], art_loi_t[-1]))
    frames_t = np.linspace(t_min, t_max, N_FRAMES)

    if de440s_moon_t is not None:
        _emx = lambda t: np.interp(t, de440s_moon_t, de440s_moon_x)
        _emy = lambda t: np.interp(t, de440s_moon_t, de440s_moon_y)
    else:
        _emx = lambda t: np.interp(t, cap_t, cap_mx)
        _emy = lambda t: np.interp(t, cap_t, cap_my)
    cap_xmc     = cap_x - cap_mx;              cap_ymc     = cap_y - cap_my
    loi_xmc     = loi_x     - _emx(loi_t);     loi_ymc     = loi_y     - _emy(loi_t)
    art_xmc     = art_x     - _emx(art_t);     art_ymc     = art_y     - _emy(art_t)
    art_loi_xmc = art_loi_x - _emx(art_loi_t); art_loi_ymc = art_loi_y - _emy(art_loi_t)

    fig = plt.figure(figsize=(19.2, 10.8), dpi=100, facecolor=BG)
    gs  = gridspec.GridSpec(1, 2, figure=fig,
                            width_ratios=[1.3, 1.0], wspace=0.03,
                            left=0.02, right=0.93, top=0.92, bottom=0.06)
    ax3 = fig.add_subplot(gs[0], projection="3d")
    ax2 = fig.add_subplot(gs[1])

