def load_artemis():
    df  = pd.read_csv(ART_CSV)
    t_s = df["time_s"].values
    sc  = df[["x_m", "y_m", "z_m"]].values * 1e-3
    mn  = df[["moon_x_m", "moon_y_m", "moon_z_m"]].values * 1e-3
    sn  = df[["sun_x_m", "sun_y_m", "sun_z_m"]].values * 1e-3
    u_sun_eci = sn[0] / np.linalg.norm(sn[0])
    R0 = compute_eci_frame(df["moon_x_m"].values, df["moon_y_m"].values,
                           df["moon_z_m"].values, t_s)

    t_rel = t_s - t_s[0]
    mask  = t_rel >= 6 * 86_400.0
    if mask.any():
        offset = int(np.where(mask)[0][0])
        end    = offset + int(np.argmin(np.linalg.norm(sc[mask], axis=1)))
        sc, mn, t_s = sc[:end+1], mn[:end+1], t_s[:end+1]
    t_days = (t_s - t_s[0]) / 86_400.0
    return (R0, u_sun_eci,
            t_days, sc[:,0], sc[:,1], sc[:,2],
            mn[:,0], mn[:,1], mn[:,2])


def _load_wsb_nd_csv(path: pathlib.Path, R0_wsb, offset_days):
    """Rotating-frame CSV → ECI days + moon ECI."""
    df = pd.read_csv(path)
    t  = df["time_nd"].values
    x, y, z = df["x_nd"].values, df["y_nd"].values, df["z_nd"].values
    xi, yi, zi = rot_em_to_eci(x, y, z, t, R0_wsb)
    mx, my, mz = moon_em_to_eci(t, R0_wsb)
    t_days = t * T_STAR / 86_400.0 + offset_days
    return t_days, xi, yi, zi, mx, my, mz


